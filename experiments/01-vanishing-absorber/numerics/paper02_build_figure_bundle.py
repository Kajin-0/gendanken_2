"""Build publication-oriented Paper-02 figure panels from canonical CSV outputs.

This script does not rerun physics.  It reads outputs generated by the checked
Paper-02 numerical scripts in the same directory and creates vector PDF plus PNG
panels.  The workflow paper02-figure-bundle.yml generates the required datasets
first, so every plotted point remains tied to executable source rather than a
manually copied research-note value.

The panels are intentionally separate files.  Final journal multi-panel layouts
can be composed in LaTeX without baking panel geometry into the scientific
plots themselves.
"""

from __future__ import annotations

import csv
from pathlib import Path

import matplotlib.pyplot as plt
import numpy as np

import realistic_geometry_closure_stress as base


OUTDIR = Path("paper02_figures")


def read_csv(path):
    with open(path, newline="", encoding="utf-8") as f:
        return list(csv.DictReader(f))


def save(fig, stem):
    OUTDIR.mkdir(parents=True, exist_ok=True)
    fig.savefig(OUTDIR / f"{stem}.pdf", bbox_inches="tight")
    fig.savefig(OUTDIR / f"{stem}.png", dpi=300, bbox_inches="tight")
    plt.close(fig)


def fig_generation_kernels():
    fig, ax = plt.subplots(figsize=(7.2, 4.6))
    zd = float(base.L_UM - 3.0)
    ax.axvspan(zd, float(base.L_UM), alpha=0.12, label="Nonuniform-velocity region")
    for mean, row in zip(base.DEPTHS, base.OPTICS):
        ax.plot(base.OPT_Z_UM, row[3], label=f"{mean:.1f} um mean")
    ax.set_xlabel("Depth z (um)")
    ax.set_ylabel("Normalized generation density")
    ax.set_xlim(0.0, float(base.L_UM))
    ax.legend(fontsize=8, ncol=2, frameon=False)
    ax.tick_params(labelsize=10)
    fig.tight_layout()
    save(fig, "fig1_generation_kernels")


def fig_apparent_diffusion_profiles():
    rows = read_csv("paper02_independent_velocity_profiles_results.csv")
    fig, ax = plt.subplots(figsize=(6.8, 4.6))
    for family in ("linear", "exponential"):
        sel = [r for r in rows if r["family"] == family or (family == "linear" and r["family"] == "uniform")]
        # include the common uniform point in both family curves
        uniform = [r for r in rows if r["family"] == "uniform"]
        fam = [r for r in rows if r["family"] == family]
        all_rows = uniform + fam
        all_rows = sorted(all_rows, key=lambda r: float(r["endpoint_ratio"]))
        x = [float(r["endpoint_ratio"]) for r in all_rows]
        y = [1e3 * float(r["effective_D_m2_per_s"]) for r in all_rows]
        ax.plot(x, y, marker="o", label=family.capitalize())
    ax.axhline(0.0, linewidth=1.0)
    ax.axvline(1.0, linewidth=1.0)
    ax.set_xlabel("Downstream endpoint velocity ratio")
    ax.set_ylabel(r"Apparent $D_{eff}$ ($10^{-3}$ m$^2$/s)")
    ax.legend(frameon=False)
    ax.tick_params(labelsize=10)
    fig.tight_layout()
    save(fig, "fig2_apparent_diffusion_velocity_profiles")


def fig_tail_ablation():
    rows = read_csv("paper02_kernel_tail_ablation_results.csv")
    rows = sorted(rows, key=lambda r: float(r["tail_scale"]))
    x = [float(r["tail_scale"]) for r in rows]
    y = [1e3 * float(r["effective_D_m2_per_s"]) for r in rows]
    fig, ax = plt.subplots(figsize=(6.8, 4.6))
    ax.plot(x, y, marker="o")
    ax.axhline(0.0, linewidth=1.0)
    ax.axvline(1.0, linewidth=1.0, linestyle="--")
    ax.set_xlabel("Generation weight inside nonuniform region (relative scale)")
    ax.set_ylabel(r"Apparent $D_{eff}$ ($10^{-3}$ m$^2$/s)")
    ax.tick_params(labelsize=10)
    fig.tight_layout()
    save(fig, "fig3_tail_ablation")


def fig_remote_overlap():
    rows = read_csv("paper02_kernel_tail_ablation_overlap.csv")
    rows = [r for r in rows if abs(float(r["tail_scale"]) - 1.0) < 1e-12]
    rows = sorted(rows, key=lambda r: int(r["channel"]))
    means = [float(r["original_mean_um"]) for r in rows]
    overlap = [100.0 * float(r["original_depletion_overlap"]) for r in rows]
    fig, ax = plt.subplots(figsize=(6.8, 4.6))
    ax.plot(means, overlap, marker="o")
    ax.set_xlabel("Mean generation depth (um)")
    ax.set_ylabel("Generation probability in nonuniform region (%)")
    ax.tick_params(labelsize=10)
    fig.tight_layout()
    save(fig, "fig3b_remote_overlap")


def fig_bias_validation():
    rows = read_csv("paper02_bias_bound_linearization.csv")
    fig, ax = plt.subplots(figsize=(6.2, 5.2))
    for family, marker in (("linear", "o"), ("exponential", "s")):
        sel = [r for r in rows if r["family"] == family]
        x = [1e3 * float(r["actual_dD_m2_per_s"]) for r in sel]
        y = [1e3 * float(r["pred_dD_m2_per_s"]) for r in sel]
        ax.scatter(x, y, marker=marker, label=family.capitalize())
    values = [1e3 * float(r["actual_dD_m2_per_s"]) for r in rows]
    lo, hi = min(values), max(values)
    pad = 0.06 * (hi - lo)
    line = np.linspace(lo - pad, hi + pad, 200)
    ax.plot(line, line, linewidth=1.0, label="Unity")
    ax.set_xlabel(r"Nonlinear inverse: $\Delta D$ ($10^{-3}$ m$^2$/s)")
    ax.set_ylabel(r"First-order prediction: $\Delta D$ ($10^{-3}$ m$^2$/s)")
    ax.legend(frameon=False)
    ax.tick_params(labelsize=10)
    fig.tight_layout()
    save(fig, "fig4_bias_law_validation")


def fig_required_snr():
    rows = read_csv("paper02_end_to_end_rejection_bands.csv")
    x = [float(r["max_frequency_hz"]) / 1e9 for r in rows]
    y = [float(r["required_rms_channel_snr_db"]) for r in rows]
    fig, ax = plt.subplots(figsize=(6.8, 4.6))
    ax.plot(x, y, marker="o")
    ax.set_xlabel("Maximum RF frequency in joint fit (GHz)")
    ax.set_ylabel("Required RMS-channel SNR (dB)")
    ax.tick_params(labelsize=10)
    fig.tight_layout()
    save(fig, "fig5_required_snr_vs_bandwidth")


def fig_refitted_diffusion():
    rows = read_csv("paper02_end_to_end_rejection_bands.csv")
    x = [float(r["max_frequency_hz"]) / 1e9 for r in rows]
    y = [1e3 * float(r["best_fit_D_m2_per_s"]) for r in rows]
    fig, ax = plt.subplots(figsize=(6.8, 4.6))
    ax.plot(x, y, marker="o")
    ax.set_xlabel("Maximum RF frequency in joint fit (GHz)")
    ax.set_ylabel(r"Re-fitted homogeneous $D$ ($10^{-3}$ m$^2$/s)")
    ax.tick_params(labelsize=10)
    fig.tight_layout()
    save(fig, "fig5b_refitted_diffusion_vs_bandwidth")


def main():
    fig_generation_kernels()
    fig_apparent_diffusion_profiles()
    fig_tail_ablation()
    fig_remote_overlap()
    fig_bias_validation()
    fig_required_snr()
    fig_refitted_diffusion()
    print(f"Wrote {len(list(OUTDIR.glob('*.pdf')))} PDF panels and PNG counterparts to {OUTDIR}")


if __name__ == "__main__":
    main()
