"""Factorial decomposition of the Paper-02 geometry/depletion confound.

The first parameter sweep found a numerically converged hidden-risk regime for
75% contact + depletion.  This script asks the next causal question before any
broader sweep: is the near-rank-one transport-like signature caused by

  (a) finite-contact geometry alone,
  (b) depletion / space-charge electrostatics alone, or
  (c) their interaction?

It also stores the full six-channel complex responses and projects each nuisance
perturbation onto the local tangent space of a best-fit rank-one sequence.  The
projection is an exploratory diagnostic of the tangent-confound theorem, not a
claim that the device is calibrated or that the theorem is novel.
"""

from __future__ import annotations

import argparse
import csv
import json
from pathlib import Path

import numpy as np
from scipy.optimize import least_squares

import realistic_geometry_closure_stress as base
import paper02_geometry_parameter_sweep as sweep


SCENARIOS = (
    base.Scenario("planar", 1.00, 0.0, 0.0),
    base.Scenario("planar_depletion", 1.00, 3.0, 0.05),
    base.Scenario("finite75", 0.75, 0.0, 0.0),
    base.Scenario("finite75_depletion", 0.75, 3.0, 0.05),
    base.Scenario("finite50", 0.50, 0.0, 0.0),
    base.Scenario("finite50_depletion", 0.50, 3.0, 0.05),
)

BEAM_SIGMA_UM = 2.0
BEAM_CENTERS_UM = (0.0, 1.0)


def best_rank_one(d: np.ndarray):
    """Complex least-squares fit d_m ~ A q^m.

    The optimization has four real degrees of freedom (complex A and q).  The
    recurrence least-squares multiplier supplies a stable initial guess.
    """
    d = np.asarray(d, dtype=complex)
    m = np.arange(len(d), dtype=float)

    denom = np.vdot(d[:-1], d[:-1]).real
    q0 = np.vdot(d[:-1], d[1:]) / denom if denom > 0 else 1.0 + 0.0j
    basis0 = q0 ** m
    denom_a = np.vdot(basis0, basis0).real
    A0 = np.vdot(basis0, d) / denom_a if denom_a > 0 else d[0]

    x0 = np.asarray([A0.real, A0.imag, q0.real, q0.imag], dtype=float)

    scale = max(float(np.linalg.norm(d)), 1e-30)

    def residual(x):
        A = x[0] + 1j * x[1]
        q = x[2] + 1j * x[3]
        r = (A * q**m - d) / scale
        return np.concatenate((r.real, r.imag))

    fit = least_squares(
        residual,
        x0,
        xtol=1e-13,
        ftol=1e-13,
        gtol=1e-13,
        max_nfev=4000,
    )

    A = fit.x[0] + 1j * fit.x[1]
    q = fit.x[2] + 1j * fit.x[3]
    model = A * q**m
    rel = float(np.linalg.norm(model - d) / max(np.linalg.norm(d), 1e-30))
    return A, q, model, rel


def tangent_projection(planar_d: np.ndarray, nuisance_d: np.ndarray):
    """Project nuisance_d-planar_d onto the local complex rank-one tangent.

    For d_m=Aq^m the complex tangent span is generated by d_m and m*d_m.
    Complex coefficients are equivalent to the four real tangent directions of
    complex A and q.
    """
    A0, q0, model0, fit_rel0 = best_rank_one(planar_d)
    A1, q1, model1, fit_rel1 = best_rank_one(nuisance_d)

    g = np.asarray(nuisance_d - planar_d, dtype=complex)
    m = np.arange(len(g), dtype=float)
    T = np.column_stack((model0, m * model0))
    coeff, *_ = np.linalg.lstsq(T, g, rcond=None)
    gt = T @ coeff
    gn = g - gt

    ng = float(np.linalg.norm(g))
    nt = float(np.linalg.norm(gt))
    nn = float(np.linalg.norm(gn))
    eps = 1e-30

    # Local normalized-perturbation curvature from the fitted planar model.
    h = g / np.where(np.abs(model0) > eps, model0, np.nan + 1j * np.nan)
    second = np.diff(h, n=2)
    first = np.diff(h)

    dq_log = np.log(q1 / q0)

    return {
        "planar_rank1_fit_rel": fit_rel0,
        "scenario_rank1_fit_rel": fit_rel1,
        "nuisance_norm_over_planar": ng / max(float(np.linalg.norm(planar_d)), eps),
        "tangent_norm_over_nuisance": nt / max(ng, eps),
        "normal_norm_over_nuisance": nn / max(ng, eps),
        "tangent_energy_fraction": (nt * nt) / max(ng * ng, eps),
        "tangent_to_normal_ratio": nt / max(nn, eps),
        "normalized_first_difference_rms": float(np.sqrt(np.nanmean(np.abs(first) ** 2))),
        "normalized_second_difference_rms": float(np.sqrt(np.nanmean(np.abs(second) ** 2))),
        "delta_log_q_real": float(dq_log.real),
        "delta_log_q_imag": float(dq_log.imag),
        "q0_real": float(q0.real),
        "q0_imag": float(q0.imag),
        "q1_real": float(q1.real),
        "q1_imag": float(q1.imag),
    }


def phase_deg(metric):
    return float(np.degrees(metric["c4"].imag))


def run(args):
    numerical = {
        "nx": args.nx,
        "nz": args.nz,
        "nx_src": args.nx_src,
        "nz_src": args.nz_src,
        "ds_um": args.ds_um,
    }

    base.V_BIAS = float(args.bias_v)
    base.X_EXTENT_UM = float(args.x_extent_um)

    by_key = {}
    metric_rows = []
    raw_rows = []
    tangent_rows = []
    decomposition_rows = []

    for center in BEAM_CENTERS_UM:
        for scenario in SCENARIOS:
            print(
                f"{scenario.name:20s} center={center:.3f} um",
                flush=True,
            )
            J, diag = sweep.currents_with_beam(
                scenario,
                BEAM_SIGMA_UM,
                center,
                **numerical,
            )
            M = base.metrics(J)
            by_key[(center, scenario.name)] = (J, diag, M)

        Jp, dp, Mp = by_key[(center, "planar")]

        for scenario in SCENARIOS:
            J, diag, M = by_key[(center, scenario.name)]
            metric_rows.extend(
                sweep.metric_rows(
                    scenario,
                    diag,
                    M,
                    Mp,
                    BEAM_SIGMA_UM,
                    center,
                )
            )

            for jf, f in enumerate(base.FREQUENCIES):
                for ch, value in enumerate(J[jf]):
                    raw_rows.append(
                        {
                            "scenario": scenario.name,
                            "beam_center_um": center,
                            "frequency_hz": float(f),
                            "channel_index": int(ch),
                            "current_real": float(value.real),
                            "current_imag": float(value.imag),
                        }
                    )

                if f > 0 and scenario.name != "planar":
                    proj = tangent_projection(np.diff(Jp[jf]), np.diff(J[jf]))
                    tangent_rows.append(
                        {
                            "scenario": scenario.name,
                            "beam_center_um": center,
                            "frequency_hz": float(f),
                            **proj,
                        }
                    )

        names = {s.name: s for s in SCENARIOS}
        for fc_label in ("75", "50"):
            no_dep_name = f"finite{fc_label}"
            dep_name = f"finite{fc_label}_depletion"
            _, _, M_no = by_key[(center, no_dep_name)]
            _, _, M_dep = by_key[(center, dep_name)]
            _, _, M_plan_dep = by_key[(center, "planar_depletion")]

            for jf, f in enumerate(base.FREQUENCIES):
                if f <= 0:
                    continue
                p = phase_deg(Mp[jf])
                contact = phase_deg(M_no[jf]) - p
                depletion = phase_deg(M_plan_dep[jf]) - p
                combined = phase_deg(M_dep[jf]) - p
                interaction = combined - contact - depletion
                target = float(base.GRADIENT_TARGET_DEG[float(f)])

                decomposition_rows.append(
                    {
                        "contact_fraction": names[no_dep_name].contact_fraction,
                        "beam_center_um": center,
                        "frequency_hz": float(f),
                        "contact_only_phase_deg": contact,
                        "depletion_only_phase_deg": depletion,
                        "combined_phase_deg": combined,
                        "interaction_phase_deg": interaction,
                        "contact_only_mimic_ratio": abs(contact / target),
                        "depletion_only_mimic_ratio": abs(depletion / target),
                        "combined_mimic_ratio": abs(combined / target),
                        "interaction_mimic_ratio": abs(interaction / target),
                    }
                )

    def write_csv(path, rows):
        path = Path(path)
        path.parent.mkdir(parents=True, exist_ok=True)
        fields = list(rows[0].keys()) if rows else []
        with path.open("w", newline="", encoding="utf-8") as f:
            w = csv.DictWriter(f, fieldnames=fields)
            w.writeheader()
            w.writerows(rows)

    write_csv(args.output_metrics, metric_rows)
    write_csv(args.output_raw, raw_rows)
    write_csv(args.output_tangent, tangent_rows)
    write_csv(args.output_decomposition, decomposition_rows)

    hidden = [
        r
        for r in metric_rows
        if r["mimic_ratio"] >= 0.5 and r["warning_margin_db"] <= 0.0
    ]

    payload = {
        "status": "CONDITIONAL factorial geometry/electrostatics stress",
        "numerical": numerical,
        "beam_sigma_um": BEAM_SIGMA_UM,
        "beam_centers_um": list(BEAM_CENTERS_UM),
        "n_metric_rows": len(metric_rows),
        "n_hidden_risk_rows": len(hidden),
        "hidden_risk_rows": [
            {
                "scenario": r["scenario"],
                "beam_center_um": r["beam_center_um"],
                "frequency_hz": r["frequency_hz"],
                "mimic_ratio": r["mimic_ratio"],
                "warning_margin_db": r["warning_margin_db"],
            }
            for r in hidden
        ],
    }

    out_summary = Path(args.output_summary)
    out_summary.parent.mkdir(parents=True, exist_ok=True)
    out_summary.write_text(json.dumps(payload, indent=2, sort_keys=True), encoding="utf-8")
    print(json.dumps(payload, indent=2, sort_keys=True))


def parser():
    p = argparse.ArgumentParser()
    p.add_argument("--bias-v", type=float, default=0.30)
    p.add_argument("--x-extent-um", type=float, default=3.5)
    p.add_argument("--nx", type=int, default=121)
    p.add_argument("--nz", type=int, default=91)
    p.add_argument("--nx-src", type=int, default=13)
    p.add_argument("--nz-src", type=int, default=41)
    p.add_argument("--ds-um", type=float, default=0.020)
    p.add_argument("--output-metrics", default="paper02_factorial_metrics.csv")
    p.add_argument("--output-raw", default="paper02_factorial_raw_complex.csv")
    p.add_argument("--output-tangent", default="paper02_factorial_tangent.csv")
    p.add_argument("--output-decomposition", default="paper02_factorial_decomposition.csv")
    p.add_argument("--output-summary", default="paper02_factorial_summary.json")
    return p


if __name__ == "__main__":
    run(parser().parse_args())
